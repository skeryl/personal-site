import { chromium } from 'playwright';
const DIR = new URL('.', import.meta.url).pathname;
const run = async () => {
	const browser = await chromium.launch();
	const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
	page.on('dialog', (d) => d.accept());
	await page.goto('http://localhost:4173/journal/calc-builder', { waitUntil: 'networkidle' });
	await page.waitForSelector('[data-slot-path="root"]');
	await page.locator('[data-preset="moodys-grade"]').click();
	await page.screenshot({ path: `${DIR}spot-dsl-preset.png` });
	const bar = page.getByLabel('Calculation expression');
	console.log('bar after preset:', await bar.inputValue());
	await bar.fill('avg(map(instrument.creditRatings, score * 2)');
	await page.screenshot({ path: `${DIR}spot-dsl-error.png` });
	await bar.fill('avg(map(instrument.creditRatings, score * 2))');
	await bar.press('Enter');
	await page.screenshot({ path: `${DIR}spot-dsl-applied.png` });
	console.log('results:', await page.locator('.result-value').allTextContents());
	await browser.close();
};
run();
